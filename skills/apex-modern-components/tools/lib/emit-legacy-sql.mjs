// Emits a classic APEX plug-in export (wwv_flow_imp / wwv_flow_imp_shared)
// stamped with the 23.1 baseline, so the same file imports into APEX
// 23.1, 23.2, 24.1, 24.2, 26.x and later (APEX imports older exports forward).

import crypto from "node:crypto";
import {
  ATTRIBUTE_TYPES,
  AVAILABLE_AS,
  CONDITION_TYPES,
  ESCAPE_MODES,
  LEGACY_BASELINE,
  PLUGIN_TYPES,
  lookup
} from "./tokens.mjs";

// Deterministic export ids so rebuilds produce stable diffs.
function makeId(...parts) {
  const hash = crypto.createHash("sha256").update(parts.join("|")).digest();
  return (hash.readBigUInt64BE(0) % 900000000000000000n) + 100000000000000000n;
}

function q(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

// Long text as wwv_flow_string.join(wwv_flow_t_varchar2(...)), one line per element.
function joined(text) {
  const lines = text.replace(/\s+$/, "").split("\n");
  if (lines.length === 1 && lines[0].length < 3000) return q(lines[0]);
  return `wwv_flow_string.join(wwv_flow_t_varchar2(\n${lines.map(q).join(",\n")}))`;
}

function bool(value) {
  return value ? "true" : "false";
}

function params(list) {
  const rows = list.filter(([, v]) => v !== null && v !== undefined);
  return rows.map(([k, v], i) => `${i === 0 ? " " : ","}${k}=>${v}`).join("\n");
}

function hexChunks(buffer) {
  const hex = buffer.toString("hex").toUpperCase();
  const chunks = [];
  for (let i = 0; i < hex.length; i += 400) chunks.push(hex.slice(i, i + 400));
  return chunks;
}

export function emitLegacySql(component, loaded) {
  const t = lookup(PLUGIN_TYPES, component.pluginType, "plugin type");
  const pluginId = makeId(component.staticId, "plugin");
  const attrIds = new Map(component.attributes.map((a) => [a.staticId, makeId(component.staticId, "attr", a.staticId)]));
  const out = [];

  out.push(
    "prompt --application/set_environment",
    "set define off verify off feedback off",
    "whenever sqlerror exit sql.sqlcode rollback",
    "--------------------------------------------------------------------------------",
    "--",
    `-- APEX Modern Components: ${component.name} (${component.staticId}) v${component.version}`,
    `-- Plug-in export stamped for APEX ${LEGACY_BASELINE.release}; imports into ${component.minApexVersion} and every later release.`,
    "-- Generated by skills/apex-modern-components/tools/build.mjs. Do not edit by hand.",
    "--",
    "-- Install: App Builder > Shared Components > Plug-ins > Import, or with SQLcl after",
    "--   apex_application_install.set_workspace('<WORKSPACE>');",
    "--   apex_application_install.set_application_id(<APP_ID>);",
    "--   apex_application_install.generate_offset;",
    "--   apex_application_install.set_schema('<PARSING_SCHEMA>');",
    "--------------------------------------------------------------------------------",
    "begin",
    "wwv_flow_imp.import_begin (",
    params([
      ["p_version_yyyy_mm_dd", q(LEGACY_BASELINE.versionDate)],
      ["p_release", q(LEGACY_BASELINE.release)],
      ["p_default_workspace_id", "apex_application_install.get_workspace_id"],
      ["p_default_application_id", "apex_application_install.get_application_id"],
      ["p_default_id_offset", "apex_application_install.get_offset"],
      ["p_default_owner", "apex_application_install.get_schema"]
    ]),
    ");",
    "end;",
    "/",
    `prompt --application/shared_components/plugins/${t.legacyFolder}/${component.staticId.toLowerCase()}`,
    "begin"
  );

  const pluginParams = [
    ["p_id", `wwv_flow_imp.id(${pluginId})`],
    ["p_plugin_type", q(t.legacy)],
    ["p_name", q(component.staticId)],
    ["p_display_name", q(component.name)]
  ];
  if (component.pluginType === "templateComponent") {
    const tc = component.templateComponent;
    const tpl = loaded.templates;
    pluginParams.push(
      ["p_supported_component_types", q(tc.availableAs.map((v) => lookup(AVAILABLE_AS, v, "availableAs").legacy).join(":"))],
      ["p_partial_template", tpl.partial ? joined(tpl.partial) : null],
      ["p_default_escape_mode", q(lookup(ESCAPE_MODES, tc.defaultEscapeMode, "escape mode").legacy)],
      ["p_translate_this_template", bool(tc.translateTemplates)],
      ["p_api_version", "1"],
      ["p_report_body_template", tpl.reportBody ? joined(tpl.reportBody) : null],
      ["p_report_row_template", tpl.reportRow ? joined(tpl.reportRow) : null],
      ["p_report_container_template", tpl.reportContainer ? joined(tpl.reportContainer) : null]
    );
  }
  if (component.pluginType === "item") {
    const it = component.item;
    pluginParams.push(
      ["p_supported_component_types", q(it.legacySupportedComponentTypes)],
      ["p_plsql_code", joined(loaded.plsql)],
      ["p_api_version", "2"],
      ["p_render_function", q(it.renderProcedureName)],
      ["p_ajax_function", it.ajaxProcedureName ? q(it.ajaxProcedureName) : null],
      ["p_standard_attributes", q(it.legacyStandardAttributes)]
    );
  }
  pluginParams.push(
    ["p_css_file_urls", component.cssFileUrls?.length ? q(component.cssFileUrls.join("\n")) : null],
    ["p_javascript_file_urls", component.jsFileUrls?.length ? q(component.jsFileUrls.join("\n")) : null],
    ["p_substitute_attributes", "true"],
    ["p_subscribe_plugin_settings", "true"],
    ["p_help_text", component.helpText ? joined(component.helpText) : null],
    ["p_version_identifier", q(component.version)],
    ["p_about_url", component.aboutUrl ? q(component.aboutUrl) : null],
    ["p_files_version", String(component.filesVersion || 1)]
  );
  out.push("wwv_flow_imp_shared.create_plugin(", params(pluginParams), ");");

  for (const attr of [...component.attributes].sort((a, b) => a.attribute - b.attribute)) {
    const type = lookup(ATTRIBUTE_TYPES, attr.type, "attribute type").legacy;
    const dep = attr.dependsOn;
    const attrParams = [
      ["p_id", `wwv_flow_imp.id(${attrIds.get(attr.staticId)})`],
      ["p_plugin_id", `wwv_flow_imp.id(${pluginId})`],
      ["p_attribute_scope", q("COMPONENT")],
      ["p_attribute_sequence", String(attr.attribute)],
      ["p_display_sequence", String(attr.sequence)],
      ["p_static_id", component.pluginType === "templateComponent" ? q(attr.staticId) : null],
      ["p_prompt", q(attr.name)],
      ["p_attribute_type", q(type)],
      ["p_is_required", bool(attr.required)],
      ["p_default_value", attr.default !== undefined && attr.default !== null ? q(attr.default) : null],
      ["p_escape_mode", attr.escapeMode ? q(lookup(ESCAPE_MODES, attr.escapeMode, "escape mode").legacy) : null],
      ["p_is_translatable", bool(attr.translatable)],
      ["p_depending_on_attribute_id", dep ? `wwv_flow_imp.id(${attrIds.get(dep.attribute)})` : null],
      ["p_depending_on_has_to_exist", dep ? "true" : null],
      ["p_depending_on_condition_type", dep ? q(lookup(CONDITION_TYPES, dep.condition, "condition type").legacy) : null],
      ["p_depending_on_expression", dep ? q(dep.value ?? (dep.list || []).join(",")) : null],
      ["p_lov_type", attr.type === "selectList" ? q("STATIC") : null],
      ["p_help_text", attr.helpText ? joined(attr.helpText) : null]
    ];
    if (dep && !attrIds.has(dep.attribute)) {
      throw new Error(`${component.staticId}.${attr.staticId} depends on unknown attribute ${dep.attribute}`);
    }
    out.push("wwv_flow_imp_shared.create_plugin_attribute(", params(attrParams), ");");
    for (const entry of attr.entries || []) {
      out.push(
        "wwv_flow_imp_shared.create_plugin_attr_value(",
        params([
          ["p_id", `wwv_flow_imp.id(${makeId(component.staticId, "attr", attr.staticId, "value", entry.return)})`],
          ["p_plugin_attribute_id", `wwv_flow_imp.id(${attrIds.get(attr.staticId)})`],
          ["p_display_sequence", String(entry.sequence)],
          ["p_display_value", q(entry.display)],
          ["p_return_value", q(entry.return)]
        ]),
        ");"
      );
    }
  }
  out.push("end;", "/");

  for (const file of loaded.files) {
    out.push(
      "begin",
      "wwv_flow_imp.g_varchar2_table := wwv_flow_imp.empty_varchar2_table;",
      ...hexChunks(file.content).map((c, i) => `wwv_flow_imp.g_varchar2_table(${i + 1}) := '${c}';`),
      "end;",
      "/",
      "begin",
      "wwv_flow_imp_shared.create_plugin_file(",
      params([
        ["p_id", `wwv_flow_imp.id(${makeId(component.staticId, "file", file.fileName)})`],
        ["p_plugin_id", `wwv_flow_imp.id(${pluginId})`],
        ["p_file_name", q(file.fileName)],
        ["p_mime_type", q(file.mimeType)],
        ["p_file_charset", q("utf-8")],
        ["p_file_content", "wwv_flow_imp.varchar2_to_blob(wwv_flow_imp.g_varchar2_table)"]
      ]),
      ");",
      "end;",
      "/"
    );
  }

  out.push(
    "prompt --application/end_environment",
    "begin",
    "wwv_flow_imp.import_end(p_auto_install_sup_obj => nvl(wwv_flow_application_install.get_auto_install_sup_obj, false));",
    "commit;",
    "end;",
    "/",
    "set verify on feedback on define on",
    "prompt  ...done"
  );
  return out.join("\n") + "\n";
}
