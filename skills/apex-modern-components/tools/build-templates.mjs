#!/usr/bin/env node
// Validates and packages the creative theme templates in theme-templates/.
//
//   node tools/build-templates.mjs                 write dist/, READMEs and the catalog
//   node tools/build-templates.mjs --check         fail if anything is invalid or stale (CI)
//   node tools/build-templates.mjs --only <slug>   validate and build one template
//
// Per template (theme-templates/<slug>/dist/):
//   apexlang/shared-components/themes/universal-theme/{list,region}-templates/amc-<slug>.apx
//   apexlang/shared-components/static-files/amc-templates/amc-tpl-<slug>.{css,js}
//   apexlang/static-files.snippet.apx
//   legacy/amc_tpl_<slug>.sql                       APEX 23.1+ component export
// Pack: theme-templates/dist/legacy/install_amc_templates.sql, assets/templates.catalog.json

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  STATIC_FOLDER, apexlangPath, componentId, emitApexlang, legacyBody, legacyFooter, legacyHeader,
  listTemplateDirs, loadTemplate, staticFilesSnippet, validateTemplate
} from "./lib/theme-templates.mjs";

const SKILL_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.join(SKILL_ROOT, "theme-templates");
const args = process.argv.slice(2);
const check = args.includes("--check");
const only = args.includes("--only") ? args[args.indexOf("--only") + 1] : null;

let dirs = listTemplateDirs(ROOT);
if (only) dirs = dirs.filter((d) => path.basename(d) === only);
if (only && !dirs.length) {
  console.error(`no template folder theme-templates/${only}`);
  process.exit(1);
}

const outputs = new Map();
const put = (file, content) => outputs.set(file, Buffer.isBuffer(content) ? content : Buffer.from(content));
let errorCount = 0;
const templates = [];

for (const dir of dirs) {
  let t;
  try {
    t = loadTemplate(dir);
  } catch (error) {
    console.error(`error ${path.basename(dir)}: cannot load: ${error.message}`);
    errorCount++;
    continue;
  }
  const { errors, warnings } = validateTemplate(t);
  warnings.forEach((w) => console.warn(`warn  ${w}`));
  errors.forEach((e) => console.error(`error ${e}`));
  if (errors.length) { errorCount += errors.length; continue; }
  templates.push(t);

  const dist = path.join(dir, "dist");
  put(path.join(dist, "apexlang", apexlangPath(t)), emitApexlang(t));
  for (const f of t.files) put(path.join(dist, "apexlang", "shared-components", "static-files", STATIC_FOLDER, f.name), f.content);
  put(path.join(dist, "apexlang", "static-files.snippet.apx"), staticFilesSnippet(t));
  put(path.join(dist, "legacy", `amc_tpl_${t.slug.replace(/-/g, "_")}.sql`),
    [...legacyHeader(`${t.spec.kind === "list" ? "List" : "Region"} Template "${t.spec.name}"`), ...legacyBody(t), ...legacyFooter()].join("\n"));
  put(path.join(dir, "README.md"), readme(t));
}

if (!only && templates.length) {
  put(path.join(ROOT, "dist", "legacy", "install_amc_templates.sql"),
    [...legacyHeader(`all ${templates.length} creative theme templates`), ...templates.flatMap(legacyBody), ...legacyFooter()].join("\n"));
  put(path.join(SKILL_ROOT, "assets", "templates.catalog.json"), JSON.stringify({
    generatedBy: "tools/build-templates.mjs",
    templates: templates.map((t) => ({
      slug: t.slug, kind: t.spec.kind, name: t.spec.name, staticId: t.spec.staticId, apexlangId: componentId(t),
      direction: t.spec.direction, version: t.spec.version, minApexVersion: t.spec.minApexVersion,
      description: t.spec.description, useFor: t.spec.useFor, keywords: t.spec.keywords || [],
      attributes: t.spec.attributes || {},
      templateOptions: (t.spec.templateOptions || []).map((o) => ({ name: o.name, cssClass: o.cssClass })),
      apexlang: path.posix.join("theme-templates", t.slug, "dist", "apexlang"),
      legacySql: path.posix.join("theme-templates", t.slug, "dist", "legacy", `amc_tpl_${t.slug.replace(/-/g, "_")}.sql`)
    }))
  }, null, 2) + "\n");
}

if (errorCount) {
  console.error(`${errorCount} error(s)`);
  process.exit(1);
}

let stale = 0;
for (const [file, buf] of outputs) {
  if (fs.existsSync(file) && fs.readFileSync(file).equals(buf)) continue;
  if (check) { console.error(`stale ${path.relative(SKILL_ROOT, file)}`); stale++; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buf);
}
if (stale) { console.error("theme template output is stale: run node tools/build-templates.mjs"); process.exit(1); }
console.log(`ok    ${templates.length} theme template(s)`);

function readme(t) {
  const s = t.spec;
  const kindLabel = s.kind === "list" ? "List Template" : "Region Template";
  const lines = [
    `# ${s.name}`,
    "",
    `<!-- Generated by tools/build-templates.mjs from template.json. Do not edit by hand. -->`,
    "",
    `**${kindLabel}** for Universal Theme · direction: ${s.direction} · APEX ${s.minApexVersion}+ · v${s.version}`,
    "",
    s.description,
    "",
    `**Use it for:** ${s.useFor}`,
    "",
    "## Install",
    "",
    "- **APEX 23.1 to 25.x (or any version, through the Builder):** App Builder > your app > Shared Components >",
    `  Export/Import > Import \`dist/legacy/amc_tpl_${t.slug.replace(/-/g, "_")}.sql\` (Component Export). It creates the`,
    `  template in Universal Theme and its Static Application File(s) in \`${STATIC_FOLDER}/\`.`,
    `- **APEX 26.1+ (APEXlang):** copy \`dist/apexlang/${apexlangPath(t)}\` and`,
    `  \`dist/apexlang/shared-components/static-files/${STATIC_FOLDER}/\` into the app, add the entries from`,
    "  `dist/apexlang/static-files.snippet.apx` to `shared-components/static-files.apx`, then run the apexlang gates.",
    "",
    "## Use",
    "",
    s.kind === "list"
      ? `Create or pick a List (Shared Components > Lists), add a **List** region and set **Appearance > List Template** to **${s.name}**. In APEXlang: \`componentAppearance { listTemplate: @${componentId(t)} }\`.`
      : `On any region, set **Appearance > Template** to **${s.name}**. In APEXlang: \`appearance { template: @${componentId(t)} }\`.`,
    "",
    s.helpText,
    ""
  ];
  if (s.kind === "list" && Object.keys(s.attributes || {}).length) {
    lines.push("## List entry attributes", "", "| Attribute | Meaning |", "|---|---|",
      ...Object.entries(s.attributes).map(([k, v]) => `| ${k.toUpperCase()} | ${v} |`), "");
  }
  if ((s.templateOptions || []).length) {
    lines.push("## Template options", "", "| Option | Class | What it does |", "|---|---|---|",
      ...s.templateOptions.map((o) => `| ${o.name} | \`${o.cssClass}\` | ${o.help.replace(/\n/g, " ")} |`), "");
  }
  if (s.source) lines.push(`Adapted from ${s.source.author || s.source.url} (${s.source.license}).`, "");
  lines.push("Status: validated offline (library rules, apexlang formatter). Not yet imported into a live APEX instance.", "");
  return lines.join("\n");
}
